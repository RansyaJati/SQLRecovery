using System.Text;
using SQLRecovery.Core.Schema;
using SQLRecovery.Core.SqlTypes;

namespace SQLRecovery.Export;

public sealed class SqlScriptExporter : IExporter
{
    public ExportFormat Format => ExportFormat.SqlScript;
    public string FileExtension => ".sql";
    public string DisplayName => "SQL script (CREATE TABLE + INSERT)";

    public async Task ExportAsync(
        TableSchema table,
        IEnumerable<object?[]> rows,
        string destinationPath,
        ExportOptions options,
        IProgress<double>? progress = null,
        CancellationToken cancellationToken = default)
    {
        var directory = Path.GetDirectoryName(destinationPath);

        if (!string.IsNullOrEmpty(directory))
            Directory.CreateDirectory(directory);

        await using var stream = new FileStream(destinationPath, FileMode.Create, FileAccess.Write, FileShare.Read);
        await using var writer = new StreamWriter(stream, options.Encoding) { NewLine = options.NewLine };

        var dialect = options.SqlDialect;
        string tableName = ValueFormatter.QuoteQualified(table, options.TableNameOverride, dialect);
        string dialectName = dialect switch
        {
            SqlDialect.MySql => "MySQL / MariaDB",
            SqlDialect.PostgreSql => "PostgreSQL",
            _ => "SQL Server (T-SQL)"
        };

        await writer.WriteLineAsync($"-- Generated by SQL Recovery Tool");
        await writer.WriteLineAsync($"-- Dialect: {dialectName}");
        await writer.WriteLineAsync($"-- Table: {table.FullName} ({table.RowCount:N0} rows estimated)");
        await writer.WriteLineAsync($"-- Generated: {DateTime.Now:O}");

        if (dialect == SqlDialect.SqlServer)
        {
            await writer.WriteLineAsync("GO");
            await writer.WriteLineAsync();
        }
        else if (dialect == SqlDialect.MySql)
        {
            await writer.WriteLineAsync();
            await writer.WriteLineAsync("SET NAMES utf8mb4;");
            await writer.WriteLineAsync("SET FOREIGN_KEY_CHECKS = 0;");
            await writer.WriteLineAsync();
        }
        else
        {
            await writer.WriteLineAsync();
        }

        if (options.IncludeCreateTable)
        {
            if (dialect == SqlDialect.SqlServer)
            {
                await writer.WriteLineAsync($"IF OBJECT_ID(N'{table.SchemaName}.{table.Name}', N'U') IS NULL");
                await writer.WriteLineAsync($"CREATE TABLE {tableName} (");
                await writer.WriteLineAsync(string.Join("," + options.NewLine,
                    table.Columns.Select(c => BuildColumnDefinition(c, dialect))));
                await writer.WriteLineAsync(");");
                await writer.WriteLineAsync("GO");
            }
            else if (dialect == SqlDialect.MySql)
            {
                await writer.WriteLineAsync($"CREATE TABLE IF NOT EXISTS {tableName} (");
                await writer.WriteLineAsync(string.Join("," + options.NewLine,
                    table.Columns.Select(c => BuildColumnDefinition(c, dialect))));
                await writer.WriteLineAsync(") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;");
            }
            else // PostgreSql
            {
                await writer.WriteLineAsync($"CREATE TABLE IF NOT EXISTS {tableName} (");
                await writer.WriteLineAsync(string.Join("," + options.NewLine,
                    table.Columns.Select(c => BuildColumnDefinition(c, dialect))));
                await writer.WriteLineAsync(");");
            }

            await writer.WriteLineAsync();
        }

        var writableColumns = table.Columns
            .Select((column, index) => (Column: column, Index: index))
            .Where(x => !x.Column.IsComputed)
            .ToList();

        string columnList = string.Join(", ", writableColumns.Select(x => ValueFormatter.QuoteIdentifier(x.Column.Name, dialect)));

        int batchSize = Math.Max(1, options.InsertBatchSize);
        var batch = new StringBuilder();
        long count = 0;
        long expected = table.RowCount;

        await foreach (var row in ReadRowsAsync(rows, cancellationToken))
        {
            if (batch.Length == 0)
            {
                batch.Append($"INSERT INTO {tableName} ({columnList}) VALUES");
                batch.Append(options.NewLine);
            }
            else
            {
                batch.Append(',');
                batch.Append(options.NewLine);
            }

            var literalBuilder = new StringBuilder("(");
            for (int i = 0; i < writableColumns.Count; i++)
            {
                if (i > 0)
                    literalBuilder.Append(", ");

                int columnIndex = writableColumns[i].Index;
                var value = columnIndex < row.Length ? row[columnIndex] : null;
                literalBuilder.Append(ValueFormatter.ToSqlLiteral(value, writableColumns[i].Column, dialect));
            }

            literalBuilder.Append(')');
            batch.Append(literalBuilder);

            count++;

            if (count % batchSize == 0)
            {
                batch.Append(';');
                await writer.WriteLineAsync(batch.ToString());
                if (dialect == SqlDialect.SqlServer)
                    await writer.WriteLineAsync("GO");
                batch.Clear();
                progress?.Report(expected > 0 ? Math.Min(1.0, (double)count / expected) : 0);
            }
            else if (expected > 0 && count % 2000 == 0)
            {
                progress?.Report(Math.Min(1.0, (double)count / expected));
            }
        }

        if (batch.Length > 0)
        {
            batch.Append(';');
            await writer.WriteLineAsync(batch.ToString());
            if (dialect == SqlDialect.SqlServer)
                await writer.WriteLineAsync("GO");
        }

        if (dialect == SqlDialect.MySql)
        {
            await writer.WriteLineAsync();
            await writer.WriteLineAsync("SET FOREIGN_KEY_CHECKS = 1;");
        }

        await writer.WriteLineAsync();
        await writer.WriteLineAsync($"-- Rows written: {count:N0}");
        await writer.FlushAsync(cancellationToken);
        progress?.Report(1.0);
    }

    private static string BuildColumnDefinition(ColumnDefinition column, SqlDialect dialect)
    {
        var builder = new StringBuilder();
        builder.Append("    ");
        builder.Append(ValueFormatter.QuoteIdentifier(column.Name, dialect));
        builder.Append(' ');
        builder.Append(SqlTypeMapper.GetColumnType(column, dialect));

        if (!column.IsNullable)
            builder.Append(" NOT NULL");

        return builder.ToString();
    }

    private static async IAsyncEnumerable<object?[]> ReadRowsAsync(
        IEnumerable<object?[]> rows,
        [System.Runtime.CompilerServices.EnumeratorCancellation] CancellationToken cancellationToken)
    {
        foreach (var row in rows)
        {
            cancellationToken.ThrowIfCancellationRequested();
            yield return row;

            await Task.Yield();
        }
    }
}
